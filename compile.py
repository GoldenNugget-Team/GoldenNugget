from sys import platform, argv
import os
import re
import shutil # Added for the macOS fix
import subprocess
import sys
import platform as _platform_mod
import PyInstaller.__main__

target_arch = next((arg for arg in argv if arg.startswith("--target-arch=")), None)
if target_arch:
    print(f"[+] Target arch: {target_arch}")


def _package_macos_app(dist_path):
    """Zip the built .app bundle so the top-level archive entry is GoldenNugget.app.

    PyInstaller --onedir --windowed produces BOTH dist/GoldenNugget.app and a loose
    dist/GoldenNugget/ folder. Zipping the wrong one makes users extract a bare
    'Contents' folder that Finder does not treat as an app (issue #29).
    ditto --keepParent pins GoldenNugget.app as the archive root and preserves
    symlinks/resource forks, so extraction yields a proper .app bundle.
    """
    arch = None
    if target_arch:
        m = re.search(r"=([^=]+)$", target_arch)
        if m:
            arch = m.group(1)
    arch_label = arch or _platform_mod.machine()
    arch_map = {"arm64": "Apple-Silicon", "x86_64": "Intel", "universal2": "Universal"}
    arch_label = arch_map.get(arch_label, arch_label)

    app_path = os.path.join(dist_path, "GoldenNugget.app")
    if not os.path.isdir(app_path):
        print(f"[!] macOS packaging skipped: {app_path} not found")
        return

    zip_path = os.path.join(dist_path, f"GoldenNugget-macOS-{arch_label}.zip")
    subprocess.run(
        ["ditto", "-c", "-k", "--keepParent", app_path, zip_path],
        check=True,
    )
    print(f"[+] macOS app packaged: {zip_path} (extracts to GoldenNugget.app)")

# Rebuild from this checkout with portable compression. A checked-in resource
# module generated by a Zstd-enabled Qt cannot be read by Qt builds without it.
# The macOS workflow's own PySide build ships without the rcc binary; the
# checked-in module is already zlib, so it is used as is there.
rcc = shutil.which("pyside6-rcc")
rcc_result = subprocess.run([
    rcc, '--compress-algo', 'zlib', 'src/qt/resources.qrc',
    '-o', 'src/qt/resources_rc.py',
]) if rcc else None
if rcc_result is None or rcc_result.returncode != 0:
    subprocess.run(['git', 'checkout', '--', 'src/qt/resources_rc.py'])
    print("[!] pyside6-rcc is unavailable, using the checked-in resources_rc.py")

# Base PyInstaller args
args = [
'nugget_cli.py',
    '--name=GoldenNugget',
    '--icon=nugget.ico',
    '--onedir',
    '--noconfirm',
    '--collect-all=pymobiledevice3',
    '--collect-all=pillow_heif',
    '--collect-all=PIL',
    '--add-data=files/:files',
    '--copy-metadata=pyimg4',
    '--hidden-import=zeroconf',
    '--hidden-import=pyimg4',
    '--hidden-import=zeroconf._utils.ipaddress',
    '--hidden-import=zeroconf._handlers.answers',
    '--hidden-import=src.qt.resources_rc',
    '--add-data=src/qt:src/qt',
    '--add-data=awesomeui/LICENSE:licenses/awesomeUI',
    # Bundle the helper tool modules (imported lazily by the CLI wrapper).
    '--hidden-import=apply_wallpaper',
    '--hidden-import=restore_cache',
    '--hidden-import=restore',
    '--hidden-import=skip_setup',
    '--hidden-import=main_app',
]

if target_arch:
    args.append(target_arch)

# --- gn-sideload signing engine (GoldenNugget Mobile helper) ---
# mobile_helper.find_engine() looks for the engine at the PyInstaller bundle
# root (sys._MEIPASS), so it is added there as a plain binary when present.
# Universal2 mac builds NEED a UNIVERSAL engine: a single-arch slice cannot
# exec on the other half of the app's audiences. Enforced the same way as the
# portable libusb check above (tools/build_sideload_engine.sh builds it).
_engine_name = ("gn-sideload.exe" if os.name == "nt" else "gn-sideload")
_engine_path = os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    "tools", "sideload-engine", "target", "release", _engine_name)
_engine_required = (platform == "darwin"
                    and target_arch == "--target-arch=universal2")
if os.path.isfile(_engine_path):
    if platform == "darwin" and _engine_required:
        lipo_info = subprocess.run(
            ["lipo", "-info", _engine_path], capture_output=True, text=True,
            check=True).stdout
        if "x86_64" not in lipo_info or "arm64" not in lipo_info:
            raise SystemExit(
                "Universal2 build requires a UNIVERSAL gn-sideload engine; "
                "" + _engine_path + " is not one. Run: "
                "bash tools/build_sideload_engine.sh universal2")
    sep = os.pathsep
    args.append(f"--add-binary={_engine_path}{sep}.")
elif _engine_required:
    raise SystemExit(
        "Universal2 build requires the gn-sideload engine. Run: "
        "bash tools/build_sideload_engine.sh universal2")
else:
    print("[!] gn-sideload engine not bundled: tools/sideload-engine/"
          "target/release/" + _engine_name + " was not built "
          "(the helper dialog will offer to build it with cargo)")


# macOS-specific flags
if platform == "darwin":
    libusb_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), ".macos-libusb")
    libusb_dylib = os.path.join(libusb_dir, "libusb-1.0.dylib")
    if target_arch == "--target-arch=universal2" and not os.path.isfile(libusb_dylib):
        raise SystemExit("Run bash tools/build_macos_libusb.sh before building Universal2")
    if os.path.isfile(libusb_dylib):
        # ctypes dependency discovery must resolve the same portable library
        # as the explicit binary, rather than the runner's Homebrew bottle.
        os.environ["DYLD_LIBRARY_PATH"] = os.pathsep.join(filter(None, (
            libusb_dir, os.environ.get("DYLD_LIBRARY_PATH", ""))))
        args.append(f"--add-binary={libusb_dylib}:.")
        args.append(f"--add-data={os.path.join(libusb_dir, 'COPYING')}:licenses/libusb")
    
    # --- MACOS OPENSSL FIX ---
    # Delete sslpsk_pmd3's bundled OpenSSL before PyInstaller collects it.
    # This forces fallback to Python's built-in _ssl without breaking codesign.
    try:
        import sslpsk_pmd3
        sslpsk_path = os.path.dirname(sslpsk_pmd3.__file__)
        dylibs_path = os.path.join(sslpsk_path, "__dot__dylibs")
        if os.path.exists(dylibs_path):
            print(f"[-] macOS Fix: Removing conflicting bundled dylibs from {dylibs_path}")
            shutil.rmtree(dylibs_path, ignore_errors=True)
    except ImportError:
        print("[!] sslpsk_pmd3 not found, skipping macOS dylib cleanup.")
    # -------------------------

    args.append('--windowed')
    args.append('--osx-bundle-identifier=com.leemin.Nugget')

    try:
        import secrets_nugget.compile_config as compile_config
        args.append('--osx-entitlements-file=entitlements.plist')
        args.append(f"--codesign-identity={compile_config.CODESIGN_HASH}")
    except ImportError:
        print("[!] Codesign skipped: compile_config not found")

elif os.name == 'nt':
    args.append('--version-file=version.txt')
    args.append('--add-data=nugget.ico;.')

    # --- WINDOWS abi3t COMPAT FIX ---
    # cryptography >= 50 ships an abi3/abi3t wheel whose
    # cryptography/hazmat/bindings/_rust.pyd links against python3t.dll (the
    # abi3t stable-ABI stub) even on the GIL-enabled CPython 3.15 builds we ship.
    #
    # The official python.org Windows installer does NOT place python3t.dll next
    # to python3XX.dll; it installs it into a sibling 'abi3t-compat' subdirectory
    # (CPython Tools/msi/core/core_files.wxs). That directory is on no DLL search
    # path, so PyInstaller's dependency analysis cannot resolve the import,
    # silently drops it, and the frozen app dies at startup with:
    #     ImportError: DLL load failed while importing _rust:
    #     The specified module could not be found.
    #
    # CPython preloads the stub at runtime in _Py_CheckPython3t()
    # (Python/dynload_win.c), which looks for 'abi3t-compat\python3t.dll' and
    # then 'python3t.dll' next to the loaded python3XX.dll. Collecting it into
    # the bundle root - where PyInstaller already puts python3XX.dll and
    # python3.dll - satisfies that second lookup, so _rust.pyd resolves.
    python3t_sources = [
        os.path.join(sys.base_prefix, "abi3t-compat", "python3t.dll"),
        os.path.join(sys.base_prefix, "python3t.dll"),
        os.path.join(os.path.dirname(sys.executable), "abi3t-compat", "python3t.dll"),
        os.path.join(os.path.dirname(sys.executable), "python3t.dll"),
    ]
    python3t_dll = next((p for p in python3t_sources if os.path.isfile(p)), None)
    if python3t_dll:
        print(f"[+] Bundling abi3t compat DLL: {python3t_dll}")
        args.append('--add-binary')
        args.append(f"{python3t_dll};.")
    else:
        # Only fatal if the installed cryptography actually needs it - the DLL
        # name sits in _rust.pyd's import table as plain ASCII. Locate the
        # package with find_spec so we do not execute cryptography/__init__.py.
        needs_python3t = False
        try:
            import importlib.util
            spec = importlib.util.find_spec("cryptography")
            for base in getattr(spec, "submodule_search_locations", None) or []:
                rust_pyd = os.path.join(base, "hazmat", "bindings", "_rust.pyd")
                if os.path.isfile(rust_pyd):
                    with open(rust_pyd, "rb") as fh:
                        needs_python3t = b"python3t.dll" in fh.read()
                    break
        except Exception:
            pass
        if needs_python3t:
            raise SystemExit(
                "[!] cryptography requires python3t.dll (abi3t compat stub) but it was "
                "not found next to the Python installation; the frozen app would crash "
                "with 'DLL load failed while importing _rust'."
            )
        print("[!] python3t.dll not found in this Python installation; skipping "
              "(not required by the installed cryptography).")
    # --------------------------------

    try:
        import pytun_pmd3
        package_path = os.path.dirname(pytun_pmd3.__file__)
        print(f"[+] Found pytun_pmd3 at: {package_path}")
        args.append('--add-binary')
        args.append(f"{package_path}/*;pytun_pmd3")
    except ImportError:
        print("[!] ERROR: Could not import pytun_pmd3. Ensure it is installed with pip.")
        import site
        site_packages_path = site.getsitepackages()[1]
        args.append('--add-binary')
        args.append(f"{site_packages_path}/pytun_pmd3/*;pytun_pmd3")

    if os.path.isdir("ffmpeg/bin"):
        args.append('--add-data=ffmpeg/bin;ffmpeg/bin')
    else:
        print("[!] ffmpeg not bundled: folder not found")

    if os.path.isdir("idevice"):
        args.append('--add-data=idevice;idevice')
    else:
        print("[!] libimobiledevice binaries not bundled: 'idevice' folder not found")

PyInstaller.__main__.run(args)

if os.name == 'nt' and python3t_dll:
    bundled_paths = [
        os.path.join("dist", "GoldenNugget", "_internal", "python3t.dll"),
        os.path.join("dist", "GoldenNugget", "python3t.dll"),
    ]
    landed = next((p for p in bundled_paths if os.path.isfile(p)), None)
    if not landed:
        raise SystemExit(
            "[!] python3t.dll was not found in the built bundle; the Windows "
            "release would crash with 'DLL load failed while importing _rust'."
        )
    print(f"[+] Verified abi3t compat DLL in bundle: {landed}")

if platform == "darwin":
    _package_macos_app("dist")
