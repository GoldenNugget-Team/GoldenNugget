#!/usr/bin/env python3
"""Dump (selector -> method type encoding) pairs for a class inside a dyld shared cache.

Why this exists
---------------
``dyld_cache_lookup.py`` answers *who references a string*, which is enough to
call a preference key real. It is not enough to call it a **boolean**: the
SpringBoard preference accessors (``shouldDisableDockSpecular`` etc.) live in a
flat ``accessor \\0 SBKey \\0`` table that carries no type information at all,
and the property metadata (``Tq,N,V_x``) is absent -- they are class methods
generated by a macro, not properties.

The only authoritative source is the ObjC metadata itself: ``class_ro_t`` ->
``method_list_t`` -> {name, types, imp}. The frameworks are not on disk (only
inside the cache), so we parse the cache directly:

    imagesText loadAddress --[mapping table]--> file offset -> mach_header_64
    -> LC_SEGMENT_64 sections -> __objc_classlist / __objc_const / __objc_methname
    -> method_list_t (relative or absolute) -> selector + type encoding

Type encodings of interest
--------------------------
    B / c   BOOL            i / I   int / unsigned int
    q / Q   long / unsigned long   d / f   double / float
    @       object (incl. NSString, NSArray)
    v       void (a setter, ``v20@0:8B16`` -> takes a BOOL)

Usage
    python tools/dsc_objc_dump.py <cache> --image SpringBoardFoundation
    python tools/dsc_objc_dump.py <cache> --image SpringBoardFoundation --grep should
    python tools/dsc_objc_dump.py <cache> --image SpringBoardFoundation --class SBFHomeScreenDefaults
"""
from __future__ import annotations

import argparse
import re
import struct
import sys
from pathlib import Path

CHUNK = 8 * 1024 * 1024


class Cache:
    def __init__(self, path: Path):
        self.path = path
        with open(path, "rb") as fh:
            head = fh.read(0x200)
            mapping_off, mapping_cnt = struct.unpack_from("<II", head, 0x10)
            text_off, text_cnt = struct.unpack_from("<QQ", head, 0x88)

            fh.seek(mapping_off)
            raw = fh.read(mapping_cnt * 32)
            self.mappings = []
            for i in range(mapping_cnt):
                addr, size, foff, _mx, _ip = struct.unpack_from("<QQQII", raw, i * 32)
                self.mappings.append((addr, size, foff))

            fh.seek(text_off)
            raw = fh.read(text_cnt * 32)
            self.images = []  # (loadAddress, textSegmentSize, path)
            for i in range(text_cnt):
                load_addr, text_size, poff = struct.unpack_from("<QII", raw, i * 32 + 16)
                fh.seek(poff)
                buf = bytearray()
                while True:
                    c = fh.read(1)
                    if not c or c == b"\0":
                        break
                    buf += c
                self.images.append((load_addr, text_size, buf.decode("utf-8", "replace")))

    # --- address <-> file offset -------------------------------------------------
    def vm_to_file(self, addr: int) -> int | None:
        for m_addr, m_size, m_foff in self.mappings:
            if m_addr <= addr < m_addr + m_size:
                return m_foff + (addr - m_addr)
        return None

    def find_image(self, needle: str):
        for load_addr, text_size, path in self.images:
            if needle in path:
                return load_addr, text_size, path
        return None

    def read(self, addr: int, size: int) -> bytes:
        off = self.vm_to_file(addr)
        if off is None:
            raise ValueError(f"address {addr:#x} is not mapped in {self.path.name}")
        with open(self.path, "rb") as fh:
            fh.seek(off)
            return fh.read(size)

    def cstr(self, addr: int, limit: int = 512) -> str:
        if not addr:
            return ""
        out = bytearray()
        while len(out) < limit:
            b = self.read(addr + len(out), 1)
            if not b or b == b"\0":
                break
            out += b
        return out.decode("utf-8", "replace")


# --- Mach-O ----------------------------------------------------------------------
LC_SEGMENT_64 = 0x19
MH_MAGIC_64 = 0xFEEDFACF
MH_CIGAM_64 = 0xCFFAEDFE


def parse_sections(cache: Cache, load_addr: int):
    """Return {seg:sect: (vmaddr, size)} for one image."""
    hdr = cache.read(load_addr, 32)
    magic = struct.unpack_from("<I", hdr, 0)[0]
    if magic == MH_CIGAM_64:
        endian = ">"
    elif magic == MH_MAGIC_64:
        endian = "<"
    else:
        raise ValueError(f"not a 64-bit mach-o at {load_addr:#x} (magic {magic:#x})")
    ncmds, = struct.unpack_from(endian + "I", hdr, 16)
    off = 32
    out = {}
    for _ in range(ncmds):
        cmd, cmdsize = struct.unpack_from(endian + "II", cache.read(load_addr + off, 8), 0)
        body = cache.read(load_addr + off, cmdsize)
        if cmd == LC_SEGMENT_64:
            _segname = body[8:24].split(b"\0")[0].decode("ascii", "replace")
            nsects, = struct.unpack_from(endian + "I", body, 64)
            so = 72
            for _s in range(nsects):
                sectname = body[so:so + 16].split(b"\0")[0].decode("ascii", "replace")
                segn = body[so + 16:so + 32].split(b"\0")[0].decode("ascii", "replace")
                addr, size = struct.unpack_from(endian + "QQ", body, so + 32)
                out[f"{segn}.{sectname}"] = (addr, size)
                so += 80
        off += cmdsize
    return out, endian


def parse_methods(cache: Cache, addr: int, endian: str):
    """Yield (selector, type_encoding) for a method_list_t.

    ``entsizeAndFlags`` packs the entry size in bits 2..15 (mask ``0x0000FFFC``)
    together with flags in the high half; ``0x80000000`` marks a *relative*
    method list whose entries are 3 x int32 self-relative offsets instead of
    3 x 8-byte absolute pointers. Reading the size as ``& 0xFFFF`` yields 3 for
    a 12-byte entry and silently walks off into unrelated strings -- which is
    exactly the failure mode that produced garbage selectors here.
    """
    head = cache.read(addr, 8)
    entsize_raw, count = struct.unpack_from(endian + "II", head, 0)
    relative = bool(entsize_raw & 0x80000000)
    entsize = entsize_raw & 0x0000FFFC
    if entsize == 0:
        entsize = 12 if relative else 24
    out = []
    for i in range(count):
        base = addr + 8 + i * entsize
        raw = cache.read(base, entsize)
        if relative:
            name_off, type_off, _imp_off = struct.unpack_from(endian + "iii", raw, 0)
            name_a = base + name_off
            type_a = base + type_off
        else:
            name_a, type_a, _imp = struct.unpack_from(endian + "QQQ", raw, 0)
        try:
            out.append((cache.cstr(name_a), cache.cstr(type_a)))
        except ValueError:
            continue
    return out


IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")
# class_data_bits_t low bits are flags (RW_REALIZED etc.); the pointer is the rest.
FAST_DATA_MASK = 0x00007FFFFFFFFFF8


class Ro:
    """A successfully decoded class_ro_t."""

    def __init__(self, name: str, methods_addr: int):
        self.name = name
        self.methods_addr = methods_addr


def _ro_candidates(cache: Cache, endian: str, data_addr: int):
    """Yield plausible class_ro_t addresses for a class_data_bits_t payload.

    In the dyld shared cache a preoptimized class usually points straight at
    ``class_ro_t`` (RO_REALIZED set); once the runtime realizes it the bits
    point at a ``class_rw_t`` whose ``ro`` field sits at +0x8. Both shapes show
    up in a live cache depending on which file the class landed in, so probe
    both and keep whichever decodes into a plausible class name.
    """
    seen = set()
    for base in (data_addr,):
        if base in seen:
            continue
        seen.add(base)
        yield base                          # shape A: class_ro_t directly
        # shape B: class_rw_t -> ro.  ro@0x08, then class_ro_t inside it.
        try:
            ro_ptr, = struct.unpack_from(endian + "Q", cache.read(base + 8, 8), 0)
        except (ValueError, struct.error):
            continue
        ro = ro_ptr & FAST_DATA_MASK
        if ro and ro not in seen:
            seen.add(ro)
            yield ro


def dump_class(cache: Cache, sections, endian, class_addr: int):
    """Return (classname, [(sel, type)]).

    class_ro_t field offsets used below (LP64, stable since iOS 15):
        flags@0x00  instanceStart@0x04  instanceSize@0x08  reserved@0x0c
        ivarLayout@0x10  name@0x18  baseMethodList@0x20  baseProtocols@0x28
    """
    # class_t: isa(8) superclass(8) cache(16) bits(8)  -> bits @ 0x20
    try:
        raw = cache.read(class_addr + 0x20, 8)
    except ValueError:
        return None, []
    data_bits, = struct.unpack_from(endian + "Q", raw, 0)
    data_addr = data_bits & FAST_DATA_MASK
    if data_addr == 0:
        return None, []
    for ro in _ro_candidates(cache, endian, data_addr):
        try:
            name_a, methods_a = struct.unpack_from(endian + "QQ", cache.read(ro + 0x18, 16), 0)
            name = cache.cstr(name_a, 256)
        except (ValueError, struct.error):
            continue
        if not IDENT.match(name or ""):
            continue
        methods = []
        if methods_a:
            try:
                methods = parse_methods(cache, methods_a, endian)
            except (ValueError, struct.error):
                methods = []
        return name, methods
    return None, []


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cache", type=Path)
    ap.add_argument("--image", required=True, help="镜像路径子串，如 SpringBoardFoundation")
    ap.add_argument("--class", dest="cls", default=None, help="只输出该类")
    ap.add_argument("--grep", default=None, help="只输出 selector 含该子串的行")
    ap.add_argument("--typed", action="store_true",
                    help="只输出带真实类型编码的行（过滤掉 v16@0:8 这类无参 getter）")
    args = ap.parse_args()

    cache = Cache(args.cache)
    found = cache.find_image(args.image)
    if not found:
        print(f"no image matching {args.image!r}", file=sys.stderr)
        return 1
    load_addr, text_size, path = found
    print(f"image : {path}")
    print(f"load  : {load_addr:#x}  text {text_size:#x}\n")
    sections, endian = parse_sections(cache, load_addr)
    cl = sections.get("__DATA_CONST.__objc_classlist") or sections.get("__DATA.__objc_classlist")
    if not cl:
        print("no __objc_classlist", file=sys.stderr)
        return 1
    addr, size = cl
    n = size // 8
    print(f"classes: {n}")
    emitted = 0
    for i in range(n):
        ptr, = struct.unpack_from(endian + "Q", cache.read(addr + i * 8, 8), 0)
        if not ptr:
            continue
        try:
            name, methods = dump_class(cache, sections, endian, ptr)
        except (ValueError, struct.error):
            continue
        if not name:
            continue
        if args.cls and name != args.cls:
            continue
        rows = methods
        if args.grep:
            rows = [(s, t) for s, t in rows if args.grep in s]
        if args.typed:
            rows = [(s, t) for s, t in rows if not re.fullmatch(r"v16@0:8|@16@0:8|v20@0:8", t or "")]
        if not rows:
            continue
        print(f"\n=== {name} ===")
        for s, t in rows:
            print(f"   {s:<62} {t}")
            emitted += 1
    print(f"\n{emitted} method rows emitted")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
