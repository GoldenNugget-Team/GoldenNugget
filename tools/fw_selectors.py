#!/usr/bin/env python3
"""Dump ObjC selectors + type encodings from a dyld shared cache, fast.

Why not dsc_objc_dump.py
------------------------
That tool opens the cache file for *every* read and reads C strings one byte
at a time - fine for one class, unusable for a whole framework (it gets
killed). It also walks only instance methods, while the SpringBoard
preference accessors (``shouldDisableDockSpecular`` ...) are **class
methods** generated by a macro, living in the metaclass.

This tool:
  * mmaps the cache - random reads are pointer arithmetic, no syscalls;
  * walks ``__objc_classlist`` and, for every class, ALSO its metaclass
    (``class -> isa -> metaclass -> class_ro_t -> baseMethodList``), so class
    methods are included;
  * handles relative method lists (``0x80000000`` flag) like the original.

Type encodings that matter for tweaks:
    B / c   BOOL          i / I   int      q / Q   long
    d / f   double        @       object (NSString / NSArray / NSDictionary)
    v20@0:8B16   a setter taking a BOOL

Usage
    python tools/fw_selectors.py <cache> --image SpringBoardFoundation \
        --out selectors.txt [--grep Dock]
"""
from __future__ import annotations

import argparse
import mmap
import re
import struct
import sys
from pathlib import Path

LC_SEGMENT_64 = 0x19
MH_MAGIC_64 = 0xFEEDFACF
MH_CIGAM_64 = 0xCFFAEDFE
FAST_DATA_MASK = 0x00007FFFFFFFFFF8
IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


class Cache:
    """mmap-backed reader over a dyld shared cache."""

    def __init__(self, path: Path):
        self.path = path
        self.fh = open(path, "rb")
        self.map = mmap.mmap(self.fh.fileno(), 0, access=mmap.ACCESS_READ)
        head = self.map[:0x200]
        mapping_off, mapping_cnt = struct.unpack_from("<II", head, 0x10)
        text_off, text_cnt = struct.unpack_from("<QQ", head, 0x88)
        self.mappings = []
        raw = self.map[mapping_off:mapping_off + mapping_cnt * 32]
        for i in range(mapping_cnt):
            addr, size, foff = struct.unpack_from("<QQQ", raw, i * 32)[:3]
            self.mappings.append((addr, size, foff))
        self.images = []
        raw = self.map[text_off:text_off + text_cnt * 32]
        for i in range(text_cnt):
            load_addr, text_size, poff = struct.unpack_from("<QII", raw, i * 32 + 16)
            end = self.map.find(b"\0", poff)
            self.images.append((load_addr, text_size,
                                self.map[poff:end].decode("utf-8", "replace")))
        self.images.sort()

    def vm_to_file(self, addr: int):
        for m_addr, m_size, m_foff in self.mappings:
            if m_addr <= addr < m_addr + m_size:
                return m_foff + (addr - m_addr)
        return None

    def read(self, addr: int, size: int) -> bytes:
        off = self.vm_to_file(addr)
        if off is None:
            raise ValueError(f"address {addr:#x} is not mapped")
        return self.map[off:off + size]

    def cstr(self, addr: int, limit: int = 512) -> str:
        if not addr:
            return ""
        off = self.vm_to_file(addr)
        if off is None:
            return ""
        end = self.map.find(b"\0", off, min(off + limit, len(self.map)))
        if end < 0:
            end = min(off + limit, len(self.map))
        return self.map[off:end].decode("utf-8", "replace")

    def find_image(self, needle: str):
        for load_addr, text_size, path in self.images:
            if needle in path:
                return load_addr, text_size, path
        return None


def parse_sections(cache: Cache, load_addr: int):
    hdr = cache.read(load_addr, 32)
    magic = struct.unpack_from("<I", hdr, 0)[0]
    if magic == MH_CIGAM_64:
        endian = ">"
    elif magic == MH_MAGIC_64:
        endian = "<"
    else:
        raise ValueError(f"not a 64-bit mach-o at {load_addr:#x}")
    ncmds, = struct.unpack_from(endian + "I", hdr, 16)
    off = 32
    out = {}
    for _ in range(ncmds):
        cmd, cmdsize = struct.unpack_from(endian + "II", cache.read(load_addr + off, 8), 0)
        body = cache.read(load_addr + off, cmdsize)
        if cmd == LC_SEGMENT_64:
            _segname = body[8:24].split(b"\0")[0].decode("ascii", "replace")
            nsects, = struct.unpack_from(endian + "I", body, 64)
            so = 72
            for _s in range(nsects):
                sectname = body[so:so + 16].split(b"\0")[0].decode("ascii", "replace")
                segn = body[so + 16:so + 32].split(b"\0")[0].decode("ascii", "replace")
                addr, size = struct.unpack_from(endian + "QQ", body, so + 32)
                out[f"{segn}.{sectname}"] = (addr, size)
                so += 80
        off += cmdsize
    return out, endian


def parse_methods(cache: Cache, addr: int, endian: str):
    """[(selector, type)] for a method_list_t, relative or absolute."""
    head = cache.read(addr, 8)
    entsize_raw, count = struct.unpack_from(endian + "II", head, 0)
    relative = bool(entsize_raw & 0x80000000)
    entsize = entsize_raw & 0x0000FFFC
    if entsize == 0:
        entsize = 12 if relative else 24
    if count > 100000:  # corrupt list guard
        return []
    out = []
    for i in range(count):
        base = addr + 8 + i * entsize
        raw = cache.read(base, entsize)
        if relative:
            name_off, type_off, _imp_off = struct.unpack_from(endian + "iii", raw, 0)
            name_a, type_a = base + name_off, base + type_off
        else:
            name_a, type_a, _imp = struct.unpack_from(endian + "QQQ", raw, 0)
        try:
            out.append((cache.cstr(name_a), cache.cstr(type_a)))
        except ValueError:
            continue
    return out


def ro_methods(cache: Cache, ro_addr: int, endian: str):
    """baseMethodList of a class_ro_t (name@0x18, methods@0x20)."""
    try:
        name_a, methods_a = struct.unpack_from(
            endian + "QQ", cache.read(ro_addr + 0x18, 16), 0)
        name = cache.cstr(name_a, 256)
    except (ValueError, struct.error):
        return None, []
    if not IDENT.match(name or ""):
        return None, []
    methods = []
    if methods_a:
        try:
            methods = parse_methods(cache, methods_a, endian)
        except (ValueError, struct.error):
            methods = []
    return name, methods


def class_rows(cache: Cache, endian: str, class_addr: int):
    """(classname, is_class_method, selector, type) for instance + class methods."""
    try:
        isa, = struct.unpack_from(endian + "Q", cache.read(class_addr, 8), 0)
        bits, = struct.unpack_from(endian + "Q", cache.read(class_addr + 0x20, 8), 0)
    except (ValueError, struct.error):
        return
    data_addr = bits & FAST_DATA_MASK
    if not data_addr:
        return
    rows = []
    # instance methods: class_ro_t (directly, or via class_rw_t.ro @ +0x8)
    for ro in (data_addr,):
        name, methods = ro_methods(cache, ro, endian)
        if name:
            for sel, typ in methods:
                rows.append((name, False, sel, typ))
            break
        try:
            ro_ptr, = struct.unpack_from(endian + "Q", cache.read(data_addr + 8, 8), 0)
        except (ValueError, struct.error):
            ro_ptr = 0
        ro2 = ro_ptr & FAST_DATA_MASK
        if ro2:
            name, methods = ro_methods(cache, ro2, endian)
            if name:
                for sel, typ in methods:
                    rows.append((name, False, sel, typ))
                break
    # class methods: the metaclass
    if isa:
        try:
            mbits, = struct.unpack_from(endian + "Q", cache.read(isa + 0x20, 8), 0)
        except (ValueError, struct.error):
            mbits = 0
        mdata = mbits & FAST_DATA_MASK
        if mdata:
            mname, methods = ro_methods(cache, mdata, endian)
            if not mname:
                try:
                    ro_ptr, = struct.unpack_from(endian + "Q", cache.read(mdata + 8, 8), 0)
                    mname, methods = ro_methods(cache, ro_ptr & FAST_DATA_MASK, endian)
                except (ValueError, struct.error):
                    pass
            if mname:
                for sel, typ in methods:
                    rows.append((mname, True, sel, typ))
    yield from rows


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("cache", type=Path)
    ap.add_argument("--image", required=True)
    ap.add_argument("--grep", default=None)
    ap.add_argument("--out", type=Path)
    args = ap.parse_args()

    cache = Cache(args.cache)
    found = cache.find_image(args.image)
    if not found:
        print(f"no image matching {args.image!r}", file=sys.stderr)
        return 1
    load_addr, text_size, path = found
    sections, endian = parse_sections(cache, load_addr)
    cl = sections.get("__DATA_CONST.__objc_classlist") or sections.get("__DATA.__objc_classlist")
    if not cl:
        print("no __objc_classlist", file=sys.stderr)
        return 1
    addr, size = cl
    n = size // 8
    print(f"image : {path}")
    print(f"classes: {n}")

    rows = []
    for i in range(n):
        ptr, = struct.unpack_from(endian + "Q", cache.read(addr + i * 8, 8), 0)
        if not ptr:
            continue
        try:
            rows.extend(class_rows(cache, endian, ptr))
        except (ValueError, struct.error):
            continue
    if args.grep:
        rows = [r for r in rows if args.grep in r[2]]
    lines = [f"{'+' if cls_m else '-'} {name:<40} {sel:<62} {typ}"
             for name, cls_m, sel, typ in rows]
    text = "\n".join(lines) + "\n"
    if args.out:
        args.out.write_text(text)
        print(f"{len(rows)} method rows -> {args.out}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
