def _research_entry(member, title, key, reason, description):
    return _t(member, Section.INTERNAL, title + ' (Research Only)', None, key,
              value=None, experimental=True, show_when_unavailable=True,
              unavailable_reason=reason, description=description, warning=reason,
              factory=lambda: _research_tweak(key, reason))


